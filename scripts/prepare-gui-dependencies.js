const fs = require('fs');
const path = require('path');
const {spawnSync} = require('child_process');

const root = path.resolve(__dirname, '..');

const resolveGuiRoot = () => {
    const candidates = [
        process.env.OPENBLOCK_GUI_PATH,
        path.resolve(root, '..', 'openblock-gui')
    ].filter(Boolean);

    try {
        candidates.push(path.dirname(require.resolve('openblock-gui/package.json')));
    } catch (error) {
        // The validation below reports a clearer error when no GUI source is available.
    }

    return candidates.find(candidate =>
        fs.existsSync(path.join(candidate, 'scripts', 'apply-scratch-paint-patch.js'))
    );
};

const guiRoot = resolveGuiRoot();
if (!guiRoot) {
    throw new Error('Could not find openblock-gui translation patch script.');
}

const patchScript = path.join(guiRoot, 'scripts', 'apply-scratch-paint-patch.js');
const patchSupportsExternalDependencies = fs.readFileSync(patchScript, 'utf8')
    .includes('OPENBLOCK_PATCH_DEPENDENCIES_ROOT');

if (patchSupportsExternalDependencies) {
    const result = spawnSync(process.execPath, [patchScript], {
        cwd: guiRoot,
        env: Object.assign({}, process.env, {
            OPENBLOCK_PATCH_DEPENDENCIES_ROOT: root,
            OPENBLOCK_PATCH_DEPENDENCIES_ONLY: '1'
        }),
        encoding: 'utf8',
        stdio: 'inherit'
    });

    if (result.error) throw result.error;
    if (result.status !== 0) {
        throw new Error(`openblock-gui dependency patch failed with exit code ${result.status}.`);
    }
}

const scratchMessagesFile = path.join(
    root,
    'node_modules',
    'openblock-blocks',
    'msg',
    'scratch_msgs.js'
);
const translationsFile = path.join(
    root,
    'node_modules',
    'openblock-l10n',
    'editor',
    'blocks',
    'pt-br.json'
);
const localeMarker = 'Blockly.ScratchMsgs.locales["pt-br"] =';
const localeAssignment = `${localeMarker}\n${JSON.stringify(
    JSON.parse(fs.readFileSync(translationsFile, 'utf8')),
    null,
    4
)};\n`;
let scratchMessages = fs.readFileSync(scratchMessagesFile, 'utf8');
const localeStart = scratchMessages.indexOf(localeMarker);
if (localeStart === -1) {
    scratchMessages = `${scratchMessages.trimEnd()}\n${localeAssignment}`;
} else {
    const nextLocale = scratchMessages.indexOf(
        'Blockly.ScratchMsgs.locales["',
        localeStart + localeMarker.length
    );
    scratchMessages = `${scratchMessages.slice(0, localeStart)}${localeAssignment}${
        nextLocale === -1 ? '' : scratchMessages.slice(nextLocale)
    }`;
}
fs.writeFileSync(scratchMessagesFile, scratchMessages);

const requiredMessages = [
    'Blockly.ScratchMsgs.locales["pt-br"]',
    '"EVENT_WHENARDUINOBEGIN": "quando o Arduino iniciar"'
];

requiredMessages.forEach(message => {
    if (!scratchMessages.includes(message)) {
        throw new Error(`Desktop Blockly translation is missing: ${message}`);
    }
});

const generatedCodeHeaders = [
    [
        path.join(root, 'node_modules', 'openblock-blocks', 'arduino_compressed.js'),
        '// generated by DoGo Block\\n'
    ],
    [
        path.join(root, 'node_modules', 'openblock-blocks', 'python_compressed.js'),
        '# generated by DoGo Block\\n'
    ]
];
generatedCodeHeaders.forEach(([file, header]) => {
    if (!fs.readFileSync(file, 'utf8').includes(header)) {
        throw new Error(`Desktop generator branding is missing from ${file}: ${header}`);
    }
});

const arduinoGenerator = fs.readFileSync(
    path.join(root, 'node_modules', 'openblock-blocks', 'arduino_compressed.js'),
    'utf8'
);
if (!arduinoGenerator.includes('__dogoblockDigitalWriteSetupOnly')) {
    throw new Error('Desktop Arduino generator does not configure digital output in setup().');
}
if (!arduinoGenerator.includes('arduino_serial_serialReadData=function') ||
    !arduinoGenerator.includes('return["Serial.read()",Blockly.Arduino.ORDER_ATOMIC]')) {
    throw new Error('Desktop Arduino generator is missing serial byte reading support.');
}

console.log('Desktop GUI dependencies, PT-BR translations and DoGo Block branding are ready.');
